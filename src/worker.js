/* ─────────────────────────────────────────────
 * Lead proxy guards. The webhook URLs are Worker secrets, but the proxy
 * itself must not let anyone script arbitrary CRM entries: same-site origin
 * only, small JSON bodies, a plausible lead shape, a best-effort per-isolate
 * rate limit and a short duplicate window. Form contents are never logged.
 * Pair with a Cloudflare WAF rate-limiting rule on /api/* (docs/ANALYTICS.md).
 * ───────────────────────────────────────────── */
const LEAD_ALLOWED_ORIGINS = new Set(['https://drrajeevagarwal.co.in', 'https://www.drrajeevagarwal.co.in']);
const LEAD_MAX_BODY_BYTES = 16 * 1024;
const LEAD_RATE_LIMIT = 20;
const LEAD_RATE_WINDOW_MS = 10 * 60 * 1000;
const LEAD_DUPLICATE_WINDOW_MS = 2 * 60 * 1000;
const leadHits = new Map();
const leadSeen = new Map();

export function leadRateAllowed(key, now = Date.now()) {
  const recent = (leadHits.get(key) || []).filter((t) => now - t < LEAD_RATE_WINDOW_MS);
  if (recent.length >= LEAD_RATE_LIMIT) {
    leadHits.set(key, recent);
    return false;
  }
  recent.push(now);
  leadHits.set(key, recent);
  if (leadHits.size > 5000) leadHits.clear();
  return true;
}

export function validateLeadPayload(payload) {
  if (!payload || typeof payload !== 'object' || Array.isArray(payload)) return 'invalid_body';
  const lead = payload.lead;
  if (!lead || typeof lead !== 'object' || Array.isArray(lead)) return 'invalid_body';
  if (typeof lead.website === 'string' && lead.website.trim() !== '') return 'rejected';
  const phone = String(lead.contact_number || lead.phone || lead.whatsapp_number || '').replace(/[\s()+-]/g, '');
  if (!/^\d{10,13}$/.test(phone)) return 'invalid_phone';
  const name = typeof lead.name === 'string' ? lead.name.trim() : '';
  if (!name || name.length > 120) return 'invalid_name';
  return null;
}

function leadDuplicate(payload, now = Date.now()) {
  const lead = payload.lead || {};
  const key = `${String(lead.contact_number || lead.phone || '').replace(/\D/g, '')}:${lead.form_name || ''}`;
  const last = leadSeen.get(key);
  leadSeen.set(key, now);
  if (leadSeen.size > 5000) leadSeen.clear();
  return last !== undefined && now - last < LEAD_DUPLICATE_WINDOW_MS;
}

function jsonResponse(status, body) {
  return new Response(JSON.stringify(body), {
    status,
    headers: RESPONSE_HEADERS,
  });
}

async function readTextSafely(response) {
  try {
    return await response.text();
  } catch {
    return '';
  }
}

function requestMeta(request) {
  return {
    forwarded_for: request.headers.get('cf-connecting-ip') || request.headers.get('x-forwarded-for') || null,
    user_agent: request.headers.get('user-agent') || null,
    referer: request.headers.get('referer') || request.headers.get('referrer') || null,
  };
}

async function forwardWebhook(request, webhookUrl, labels) {
  if (request.method === 'OPTIONS') {
    return new Response(null, {
      status: 204,
      headers: RESPONSE_HEADERS,
    });
  }

  if (request.method !== 'POST') {
    return jsonResponse(405, { error: 'Method not allowed.' });
  }

  if (!LEAD_ALLOWED_ORIGINS.has(request.headers.get('origin') || '')) {
    return jsonResponse(403, { error: 'Forbidden.' });
  }

  if (Number(request.headers.get('content-length') || 0) > LEAD_MAX_BODY_BYTES) {
    return jsonResponse(413, { error: 'Payload too large.' });
  }

  if (!leadRateAllowed(request.headers.get('cf-connecting-ip') || 'unknown')) {
    return jsonResponse(429, { error: 'Too many requests. Please call the clinic instead.' });
  }

  if (!webhookUrl) {
    return jsonResponse(500, { error: `${labels.envName} is not configured.` });
  }

  let payload;
  try {
    const raw = await request.text();
    if (raw.length > LEAD_MAX_BODY_BYTES) return jsonResponse(413, { error: 'Payload too large.' });
    payload = JSON.parse(raw);
  } catch {
    return jsonResponse(400, { error: 'Invalid JSON payload.' });
  }

  const invalid = validateLeadPayload(payload);
  if (invalid === 'rejected') return jsonResponse(200, { ok: true });
  if (invalid) return jsonResponse(422, { error: 'Please check the form details and try again.' });

  if (leadDuplicate(payload)) return jsonResponse(200, { ok: true, duplicate: true });

  const forwardedPayload = {
    ...payload,
    request: requestMeta(request),
  };

  try {
    const webhookResponse = await fetch(webhookUrl, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(forwardedPayload),
    });

    if (!webhookResponse.ok) {
      // The upstream body is not echoed to the browser.
      await readTextSafely(webhookResponse);
      return jsonResponse(502, {
        error: labels.rejectedMessage,
        status: webhookResponse.status,
      });
    }

    return jsonResponse(200, { ok: true });
  } catch {
    return jsonResponse(502, { error: labels.failedMessage });
  }
}

/* ─────────────────────────────────────────────
 * /.well-known/* — agent & client discovery documents
 *
 * Without this, an unpublished discovery document falls through to the SPA
 * fallback and answers 200 with the HTML shell. An agent asking for
 * application/linkset+json or text/markdown then has to guess that a web page
 * means "absent". Serve whatever is genuinely published under .well-known and
 * answer a plain 404 for the rest.
 *
 * Routed here by run_worker_first in wrangler.toml.
 * ───────────────────────────────────────────── */

async function wellKnownResponse(request, env) {
  const assetResponse = await env.ASSETS.fetch(request);
  const contentType = assetResponse.headers.get('content-type') || '';

  // A real published document is JSON, markdown or plain text. HTML back from
  // the asset server means no such file exists and the SPA fallback answered.
  if (assetResponse.ok && !contentType.includes('text/html')) {
    return assetResponse;
  }

  return jsonResponse(404, {
    error: 'Not found.',
    detail: 'This site publishes no discovery document at this path.',
  });
}

/* ─────────────────────────────────────────────
 * Legacy WordPress URL cleanup (mirrors public/.htaccess)
 * Returns a Response for legacy paths, or null to continue normal handling.
 * ───────────────────────────────────────────── */

function gone() {
  return new Response('Gone', {
    status: 410,
    headers: { 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store' },
  });
}

function forbidden() {
  return new Response('Forbidden', {
    status: 403,
    headers: { 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store' },
  });
}

/** Absolute URL for a retired article's destination (a path here, or a full URL elsewhere). */
function retiredTarget(slug) {
  const to = Object.hasOwn(RETIRED_ARTICLE_REDIRECTS, slug) ? RETIRED_ARTICLE_REDIRECTS[slug] : null;
  if (!to) return null;
  return to.startsWith('http') ? to : `${SITE_ORIGIN}${to}`;
}

// Pages deleted by the SEO brief of 18 Oct 2026 (task 7): answer 410 Gone.
const DELETED_PAGES = new Set(['/elementor-10995', '/courses-page-copy']);

export function legacyWordPressResponse(url) {
  const { pathname, search } = url;

  // Overlapping articles retired by the SEO brief (task 9): /<slug>, /<slug>/,
  // /blog/<slug> and /blog/<slug>/ all 301 in one hop to the stronger article.
  const retired = pathname.match(/^\/(?:blog\/)?([^/]+)\/?$/);
  if (retired) {
    const target = retiredTarget(retired[1]);
    if (target) return Response.redirect(target, 301);
  }

  // Deleted pages (task 7) → 410 Gone, with or without the trailing slash.
  if (DELETED_PAGES.has(pathname.replace(/\/+$/, ''))) return gone();

  // preconception-care → /preconception (301)
  if (pathname.replace(/\/+$/, '') === '/preconception-care') {
    return Response.redirect(`${SITE_ORIGIN}/preconception`, 301);
  }

  // /learn-with-dr-rajeev-agarwal → /courses (301). The old WordPress "Course
  // Listing" page had no courses and no internal link; /courses is the real,
  // linked page on the same topic (health report 2026-10-18, item 7).
  if (/^\/learn-with-dr-rajeev-agarwal(?:\/.*)?$/i.test(pathname)) {
    return Response.redirect(`${SITE_ORIGIN}/courses${search}`, 301);
  }

  // /doctors and /doctors/<slug> → 410 Gone (placeholder team page removed 2026-10-12)
  if (/^\/doctors(?:\/|$)/i.test(pathname)) return gone();

  // WordPress attachment / post-id query params (?attachment_id= / ?p=) → 410 Gone
  if (/[?&](?:attachment_id|p)=/.test(search)) return gone();

  // xmlrpc.php → 403 Forbidden
  if (/^\/xmlrpc\.php$/i.test(pathname)) return forbidden();

  // wp-json / wp-admin / wp-login(.php) / wp-includes / wp-content → 410 Gone.
  // The trailing [/.] also catches file forms like /wp-login.php.
  // (note: /wp-styles/* are real assets and are intentionally NOT matched)
  if (/^\/wp-(?:admin|login|includes|content|json)(?:[/.]|$)/i.test(pathname)) {
    return gone();
  }

  // RSS / comment / trackback feeds (…/feed) → 301 to homepage
  if (/\/feed\/?$/i.test(pathname)) return Response.redirect(`${SITE_ORIGIN}/`, 301);

  // Author archives → 301 to About page
  if (/^\/author\/.+/i.test(pathname)) return Response.redirect(`${SITE_ORIGIN}/about-me`, 301);

  // WordPress pagination artifacts: /<parent>/page/N → /<parent>, /page/N → /
  const pageMatch = pathname.match(/^(\/.*?)?\/page\/\d+\/?$/i);
  if (pageMatch) {
    const parent = pageMatch[1] || '/';
    return Response.redirect(`${SITE_ORIGIN}${parent}`, 301);
  }

  // Retired article URLs: /blog/<slug> and /blog/<slug>/ → /<slug>/ (301).
  // Every article's canonical is the root, trailing-slash form; this keeps the
  // old URLs' backlinks and ranking history flowing to it and guarantees the
  // old form never renders a duplicate. Any single segment under /blog/ is
  // redirected, not only bundled slugs, so posts published later through the
  // admin panel are covered too. "/blog" and "/blog/" (the listing page) do
  // not match. The query string is preserved.
  const oldArticle = pathname.match(/^\/blog\/([^/]+)\/?$/);
  if (oldArticle) {
    return Response.redirect(`${SITE_ORIGIN}/${oldArticle[1]}/${search}`, 301);
  }

  return null;
}

/**
 * Map /<slug>/ — the canonical article URL — onto its prerendered file.
 *
 * html_handling = "drop-trailing-slash" (wrangler.jsonc) makes the asset layer
 * answer any "/x/" with a 307 to "/x". That is right for every other page,
 * whose canonical is the slash-less form, but an article's canonical IS the
 * slash form and a canonical URL must answer 200 in one hop. So for known
 * article slugs the Worker asks the asset layer for the slash-less path and
 * returns that document under the requested URL. "/<slug>" keeps answering
 * 200 as well; both forms carry the same self-referencing canonical, so search
 * engines consolidate on /<slug>/ without a redirect chain. Whether the bare
 * form should later 301 to the slash form is a separate decision.
 *
 * Returns the Request to hand to env.ASSETS, or null for any other path.
 */
function articleAssetRequest(request, url) {
  const match = url.pathname.match(/^\/([^/]+)\/$/);
  if (!match || !BLOG_SLUGS.has(match[1])) return null;

  const assetUrl = new URL(url);
  assetUrl.pathname = `/${match[1]}`;
  return new Request(assetUrl, request);
}

/**
 * "/x/" → 301 "/x" for every non-article path.
 *
 * html_handling = "drop-trailing-slash" already answers these with a 307 from
 * the asset layer, but a 307 is temporary: crawlers keep the slash form as the
 * indexed URL and re-fetch the redirect on every visit. Every non-article
 * page's canonical is the slash-less form, so answer a permanent 301 here,
 * before the asset layer sees the request. Articles (/<slug>/) are the one
 * exception — their canonical IS the slash form — and are left alone exactly
 * as articleAssetRequest() recognises them. The query string is preserved.
 *
 * Returns the redirect Response, or null when the path needs no redirect.
 */
export function trailingSlashRedirect(url) {
  const { pathname, search } = url;
  if (pathname.length < 2 || !pathname.endsWith('/')) return null;

  const article = pathname.match(/^\/([^/]+)\/$/);
  if (article && BLOG_SLUGS.has(article[1])) return null;

  return Response.redirect(`${SITE_ORIGIN}${pathname.replace(/\/+$/, '')}${search}`, 301);
}

/**
 * www.<host> → 301 to the apex origin, same path and query.
 *
 * The canonical origin is SITE_ORIGIN (no www). This only has an effect once
 * www.drrajeevagarwal.co.in is attached to this Worker as a custom domain or
 * route; wrangler.jsonc declares none, and the www DNS record currently points
 * at the old host, so until the owner moves it this is inert.
 *
 * Returns the redirect Response, or null for any other hostname.
 */
export function wwwRedirect(url) {
  if (!url.hostname.startsWith('www.')) return null;
  return Response.redirect(`${SITE_ORIGIN}${url.pathname}${url.search}`, 301);
}

// ─── Edge hardening (health report 2026-10-18, items 2 and 6) ──────────────
// Plain http:// on the production hosts → 301 to https://, and a baseline set
// of security headers on every response this Worker returns (it runs first
// for every request, so this covers pages, assets, redirects and /api/*).
// Local hosts (wrangler dev) are left alone.
const PRODUCTION_HOSTS = new Set(['drrajeevagarwal.co.in', 'www.drrajeevagarwal.co.in']);

// HSTS starts short (1 day) as the report recommends. Raise it to 31536000
// after a week without issues; add includeSubDomains only once every
// subdomain is confirmed to serve HTTPS.
export const SECURITY_HEADERS = {
  'Strict-Transport-Security': 'max-age=86400',
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'SAMEORIGIN',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=()',
  // Clickjacking protection only. A full script/style CSP needs testing with
  // gtag, the chatbot and YouTube embeds first, so it is deliberately not set.
  'Content-Security-Policy': "frame-ancestors 'self'; base-uri 'self'; object-src 'none'",
};

export function httpsRedirect(url) {
  if (url.protocol !== 'http:' || !PRODUCTION_HOSTS.has(url.hostname)) return null;
  return Response.redirect(`https://${url.hostname}${url.pathname}${url.search}`, 301);
}

export function withSecurityHeaders(response, url) {
  // Response.redirect() and asset responses have immutable headers; copy.
  const secured = new Response(response.body, response);
  for (const [name, value] of Object.entries(SECURITY_HEADERS)) {
    if (name === 'Strict-Transport-Security' && (url.protocol !== 'https:' || !PRODUCTION_HOSTS.has(url.hostname))) continue;
    if (!secured.headers.has(name)) secured.headers.set(name, value);
  }
  return secured;
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const toHttps = httpsRedirect(url);
    if (toHttps) return withSecurityHeaders(toHttps, url);
    return withSecurityHeaders(await handleRequest(request, env, url), url);
  },
};

async function handleRequest(request, env, url) {
  // www → apex (301) before anything else; see wwwRedirect().
  const hostRedirect = wwwRedirect(url);
  if (hostRedirect) return hostRedirect;

  // Legacy WordPress URL cleanup (301 / 410 / 403) — mirrors public/.htaccess.
  // Runs before asset pass-through so e.g. /wp-content/*.jpg 410s instead of 404-ing.
  const legacyResponse = legacyWordPressResponse(url);
  if (legacyResponse) return legacyResponse;

  if (url.pathname === '/api/lead-webhook') {
    return forwardWebhook(request, env.WEBHOOK_URL || env.VITE_WEBHOOK_URL, {
      envName: 'WEBHOOK_URL',
      rejectedMessage: 'Webhook rejected the lead payload.',
      failedMessage: 'Webhook delivery failed.',
    });
  }

  if (url.pathname === '/api/workshop-webhook') {
    return forwardWebhook(request, env.WORKSHOP_WEBHOOK, {
      envName: 'WORKSHOP_WEBHOOK',
      rejectedMessage: 'Webhook rejected the workshop payload.',
      failedMessage: 'Workshop webhook delivery failed.',
    });
  }

  if (url.pathname.startsWith('/api/')) {
    return jsonResponse(404, { error: 'API route not found.' });
  }

  if (url.pathname.startsWith('/.well-known/')) {
    return wellKnownResponse(request, env);
  }

  if (url.pathname === '/version.json') {
    const versionResponse = await env.ASSETS.fetch(request);
    const headers = new Headers(versionResponse.headers);
    headers.set('Content-Type', 'application/json; charset=utf-8');
    headers.set('Cache-Control', 'no-store, no-cache, must-revalidate, max-age=0');
    headers.set('CDN-Cache-Control', 'no-store');
    headers.set('Pragma', 'no-cache');
    headers.set('Expires', '0');

    return new Response(versionResponse.body, {
      status: versionResponse.status,
      headers,
    });
  }

  // Static assets — pass through directly
  if (STATIC_EXT.test(url.pathname)) {
    return env.ASSETS.fetch(request);
  }

  // Non-article "/x/" → 301 "/x". Replaces the asset layer's 307 for these
  // paths so the redirect is permanent; see trailingSlashRedirect().
  const slashRedirect = trailingSlashRedirect(url);
  if (slashRedirect) return slashRedirect;

  // Page routes — fetch HTML and inject SEO tags. Article URLs (/<slug>/)
  // are mapped onto their prerendered file first; see articleAssetRequest().
  const assetResponse = await env.ASSETS.fetch(articleAssetRequest(request, url) || request);
  const html = await assetResponse.text();
  let modifiedHtml = injectSeoTags(html, url.pathname);
  // Tag-filtered blog views (/blog?tag=…) stay crawlable but out of the index
  // (SEO brief task 8); /blog itself stays indexable.
  const isTagView = url.pathname === '/blog' && url.searchParams.has('tag');
  if (isTagView) {
    modifiedHtml = modifiedHtml.replace(/<meta name="robots"[^>]*>/gi, '').replace('</title>', '</title>\n    <meta name="robots" content="noindex, follow">');
  }

  const headers = new Headers(assetResponse.headers);
  headers.set('Content-Type', 'text/html; charset=utf-8');
  // HTML must revalidate so phones do not keep an old document that points
  // at an older Vite bundle. Hashed assets remain cacheable below.
  headers.set('Cache-Control', 'no-store, no-cache, must-revalidate, max-age=0');
  headers.set('CDN-Cache-Control', 'no-store');
  headers.set('Pragma', 'no-cache');
  headers.set('Expires', '0');
  if (isTagView) headers.set('X-Robots-Tag', 'noindex, follow');

  return new Response(modifiedHtml, {
    status: assetResponse.status,
    headers,
  });
}
