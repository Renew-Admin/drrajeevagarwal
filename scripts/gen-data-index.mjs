// gen-data-index — writes src/data/generated/dataIndex.js (health report item 8).
//
// pages_data.js (~1.4 MB) and blogs_data.js (~0.9 MB) used to be imported by
// the app shell, so every page — the homepage included — downloaded both.
// The shell only needs three small things from them:
//   - the set of service-page slugs (RootSlugPage routing),
//   - the set of bundled article slugs (header active tab, canonical paths),
//   - the three latest posts shown on the homepage.
// This script extracts exactly those, so the full files load only with the
// pages that render them (lazy routes in src/App.jsx). It runs before every
// build; the output is committed so `vite dev` works on a fresh clone.
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const load = (rel) => import(pathToFileURL(join(ROOT, rel)).href);

const { pagesData } = await load('src/data/pages_data.js');
const { blogsData } = await load('src/data/blogs_data.js');
const { liveBlogUpdates } = await load('src/data/live_blog_updates.js');

const servicePageSlugs = Object.keys(pagesData);
const articleSlugs = [...new Set([...liveBlogUpdates, ...blogsData].map((p) => p && p.slug).filter(Boolean))];
const homeLatestBlogs = blogsData.slice(0, 3);

const out = `// AUTO-GENERATED by scripts/gen-data-index.mjs — do not edit by hand.
// Small extracts of src/data/pages_data.js and src/data/blogs_data.js for the
// app shell; see that script for why.

export const SERVICE_PAGE_SLUGS = ${JSON.stringify(servicePageSlugs)};

export const ARTICLE_SLUGS = ${JSON.stringify(articleSlugs)};

// blogsData.slice(0, 3), unchanged, for the homepage blog section.
export const HOME_LATEST_BLOGS = ${JSON.stringify(homeLatestBlogs)};
`;
const target = join(ROOT, 'src/data/generated/dataIndex.js');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`[data-index] ${servicePageSlugs.length} service slugs, ${articleSlugs.length} article slugs, ${homeLatestBlogs.length} home posts (${Math.round(Buffer.byteLength(out) / 1024)} KiB)`);
