/**
 * Build-time SEO asset generator. Run before `vite build` / `wrangler deploy`.
 *
 * Produces two artifacts from the canonical repo data so they can never drift:
 *   1. src/data/blogSlugs.cjs — the list of live blog slugs, imported by
 *      src/worker.js to serve the canonical /<slug>/ form of every article.
 *      Emitted as .cjs so it loads identically under Node ESM, Node CJS,
 *      esbuild (wrangler), and vite without import attributes.
 *   2. public/sitemap.xml — a fresh sitemap listing every indexable route
 *      plus every blog post (with <lastmod> from the post date).
 *   3. src/data/blogMeta.cjs — real per-post title, description, image and date,
 *      keyed by slug. Before this existed, seoMeta.cjs title-cased the slug, so
 *      every post shipped a mangled title ("What Is Testosterone") instead of
 *      its real one ("Testosterone: What It Is, What It Does and Why It
 *      Matters") and all 73 descriptions were the same sentence template.
 *
 * Usage: node scripts/gen-seo-assets.mjs
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { blogsData } from '../src/data/blogs_data.js';
import { liveBlogUpdates } from '../src/data/live_blog_updates.js';
import { MENOPAUSE_PAGES, MENOPAUSE_ROUTES } from '../src/data/menopauseCare.js';
// Reuse the app's own resolvers so the image chosen for og:image and for the
// Article schema is the same one the page actually renders.
import { decodeHtml, getBlogImage, getBlogCategory, stripBlogHtml } from '../src/utils/blogPresentation.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SITE_ORIGIN = 'https://drrajeevagarwal.co.in';

// Indexable non-blog routes. Mirrors the route set that receives SEO tags in
// scripts/inject-seo-tags.mjs / src/worker.js. Keep in sync if routes change.
const STATIC_ROUTES = [
  '/', '/about-me', '/all-services', '/book-an-appointment', '/blog', '/doctors',
  '/preconception', '/preconception-workshop', '/success-stories', '/courses',
  // Service pages
  '/advanced-fertility-treatments', '/fertility-support-services', '/fibroids-solutions',
  '/healthy-aging', '/hysteroscopic-procedure', '/infertility-help', '/laparoscopic-surgery',
  '/learn-with-dr-rajeev-agarwal', '/menopause-wellness', '/pcos-care', '/period-pain-relief',
  '/sexual-pain-relief', '/urinary-incontinence', '/urinary-laser-therapy', '/vaginismus-therapy',
  '/virtual-consults', '/womens-health-check',
  // Menopause Care hub and its sub-pages. Derived from the same registry the
  // router and the page components read, so a new sub-page cannot ship without
  // a sitemap entry (and therefore without being prerendered — prerender.mjs
  // takes its route list from this sitemap).
  ...MENOPAUSE_ROUTES,
  // Policy pages (low priority)
  '/privacy-policy', '/terms-conditions', '/disclaimer-policy', '/cancellation-refund-policy',
];

// ─── Derive live blog slugs (de-duplicated, order preserved) ────────────────
// Posts come from two files and BOTH are rendered by the app — see
// STATIC_BLOGS in src/pages/BlogPost.jsx / BlogList.jsx, which merge them in
// this same order. Reading only blogs_data.js here left the newer
// live_blog_updates.js posts out of the sitemap, out of blogSlugs.cjs and out
// of the prerender pass, so with not_found_handling = "404-page" they served a
// hard 404. Keep this list identical to what the app can render.
const allPosts = [...liveBlogUpdates, ...blogsData];

const seen = new Set();
const blogPosts = [];
for (const post of allPosts) {
  if (!post || !post.slug || seen.has(post.slug)) continue;
  seen.add(post.slug);
  blogPosts.push({ ...post, date: typeof post.date === 'string' ? post.date : null });
}
const blogSlugs = blogPosts.map((p) => p.slug);

writeFileSync(
  join(ROOT, 'src/data/blogSlugs.cjs'),
  '/* eslint-disable */\n' +
  '// Auto-generated by scripts/gen-seo-assets.mjs — do not edit by hand.\n' +
  'module.exports = ' + JSON.stringify(blogSlugs, null, 2) + ';\n',
);

// ─── Per-post metadata (real titles + descriptions) ─────────────────────────

// Google renders roughly 60 characters of a title. Appending the brand to an
// already-long headline just pushes the headline itself out of the SERP, so
// only short titles get the suffix.
const BRAND_SUFFIX = ' | Dr. Rajeev Agarwal';
const TITLE_SUFFIX_BUDGET = 45;
const DESC_TARGET = 155;

function metaTitle(rawTitle) {
  const title = decodeHtml(rawTitle || '').replace(/\s+/g, ' ').trim();
  return title.length <= TITLE_SUFFIX_BUDGET ? title + BRAND_SUFFIX : title;
}

/**
 * First real prose of the post, trimmed to a whole word near DESC_TARGET.
 * Falls back to the title so a post can never emit an empty description.
 */
function metaDescription(post) {
  const text = stripBlogHtml(post.content || '').replace(/\s+/g, ' ').trim();
  if (!text) return decodeHtml(post.title || '').trim();
  if (text.length <= DESC_TARGET) return text;

  const cut = text.slice(0, DESC_TARGET);
  // Prefer ending on a sentence; otherwise fall back to the last whole word.
  const sentenceEnd = Math.max(cut.lastIndexOf('. '), cut.lastIndexOf('? '), cut.lastIndexOf('! '));
  if (sentenceEnd > 80) return cut.slice(0, sentenceEnd + 1);
  return cut.replace(/\s+\S*$/, '') + '…';
}

const blogMeta = {};
blogPosts.forEach((post, index) => {
  blogMeta[post.slug] = {
    title: metaTitle(post.title),
    // Kept separate from `title`: the Article schema wants the bare headline,
    // not the brand-suffixed <title> string.
    headline: decodeHtml(post.title || '').replace(/\s+/g, ' ').trim(),
    description: metaDescription(post),
    image: getBlogImage(post, index),
    category: getBlogCategory(post),
    date: post.date,
  };
});

writeFileSync(
  join(ROOT, 'src/data/blogMeta.cjs'),
  '/* eslint-disable */\n' +
  '// Auto-generated by scripts/gen-seo-assets.mjs — do not edit by hand.\n' +
  'module.exports = ' + JSON.stringify(blogMeta, null, 2) + ';\n',
);

// ─── Menopause Care metadata (CJS mirror) ──────────────────────────────────
// src/data/menopauseCare.js is ESM, but seoMeta.cjs and jsonLd.cjs must load
// identically under Node ESM (prerender), Node CJS (render server) and esbuild
// (wrangler). Same reason blogMeta.cjs exists: generate the .cjs from the ESM
// source rather than maintaining two hand-written copies that drift.
const menopauseSeo = {};
for (const page of MENOPAUSE_PAGES) {
  menopauseSeo[page.path] = {
    title: page.title,
    description: page.description,
    breadcrumb: page.breadcrumb,
    heading: page.heading,
    faqs: page.faqs || [],
  };
}

writeFileSync(
  join(ROOT, 'src/data/menopauseSeo.cjs'),
  '/* eslint-disable */\n' +
  '// Auto-generated by scripts/gen-seo-assets.mjs — do not edit by hand.\n' +
  '// Source of truth: src/data/menopauseCare.js\n' +
  'module.exports = ' + JSON.stringify(menopauseSeo, null, 2) + ';\n',
);

// ─── Build sitemap.xml ──────────────────────────────────────────────────────
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const isDate = (d) => typeof d === 'string' && /^\d{4}-\d{2}-\d{2}/.test(d);

const urlEntry = (loc, { lastmod, priority } = {}) =>
  [
    '  <url>',
    `    <loc>${esc(SITE_ORIGIN + loc)}</loc>`,
    lastmod ? `    <lastmod>${lastmod.slice(0, 10)}</lastmod>` : null,
    priority ? `    <priority>${priority}</priority>` : null,
    '  </url>',
  ].filter(Boolean).join('\n');

// Newest post date. Only the routes that genuinely change when a post is
// published get a <lastmod>. Stamping every static route with the build date
// would tell Search Console the whole site changed on every deploy, which
// devalues the signal — an absent lastmod is better than a false one.
const newestPostDate = blogPosts
  .map((p) => p.date)
  .filter(isDate)
  .sort()
  .pop();

const BLOG_DRIVEN_ROUTES = new Set(['/', '/blog']);

const entries = [];
for (const route of STATIC_ROUTES) {
  entries.push(urlEntry(route, {
    lastmod: BLOG_DRIVEN_ROUTES.has(route) ? newestPostDate : undefined,
    priority: route === '/' ? '1.0' : '0.8',
  }));
}
// Articles: the canonical form is /<slug>/ (site root, trailing slash) — the
// same URL seoMeta.cjs puts in the canonical tag and jsonLd.cjs in the
// BlogPosting. Never /blog/<slug>: that form is redirected, and a sitemap must
// list only URLs that answer 200.
for (const post of blogPosts) {
  entries.push(urlEntry(`/${post.slug}/`, {
    lastmod: isDate(post.date) ? post.date : undefined,
    priority: '0.7',
  }));
}

const sitemap =
  '<?xml version="1.0" encoding="UTF-8"?>\n' +
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
  entries.join('\n') +
  '\n</urlset>\n';

writeFileSync(join(ROOT, 'public/sitemap.xml'), sitemap);

// ─── Build _redirects (Cloudflare static assets) ────────────────────────────
// Articles used to live at /blog/<slug>. Those URLs are indexed and linked, so
// they must 301 to the canonical /<slug>/ rather than fall through to
// not_found_handling or — worse — render a second copy of the article.
//
// Cloudflare does not apply _redirects to requests the Worker serves, and
// wrangler.jsonc sets run_worker_first = true, so on the live site these rules
// are a fallback: src/worker.js carries the same 301 (with the query string
// preserved) and answers first. The two are kept identical so behaviour does
// not change if the Worker is ever scoped back to a prefix list.
//
// Both the bare and the trailing-slash form of every old path are emitted.
// Rules here match the request path literally — nothing normalises the slash
// first — and both forms have been linked over the years.
//
// Two literal rules per slug, not a "/blog/*" splat: a splat would also catch
// "/blog/" (the listing page) and cannot append the trailing slash the
// canonical form needs. Cloudflare allows 2,000 static rules, so two per post
// is well within budget.
const redirectPair = (from, to) => [`${from} ${to} 301`, `${from}/ ${to} 301`];

const redirectLines = [
  '# Auto-generated by scripts/gen-seo-assets.mjs — do not edit by hand.',
  '',
  '# Retired article URLs: /blog/<slug> → /<slug>/ (the canonical form)',
  ...blogSlugs.flatMap((slug) => redirectPair(`/blog/${slug}`, `/${slug}/`)),
  '',
  '# Renamed page',
  ...redirectPair('/preconception-care', '/preconception'),
  '/preconception-care/* /preconception 301',
  '',
  '# WordPress feeds and archives',
  ...redirectPair('/feed', '/'),
  '/author/* /about-me 301',
];

writeFileSync(join(ROOT, 'public/_redirects'), `${redirectLines.join('\n')}\n`);

console.log(
  `[seo-assets] wrote src/data/blogSlugs.cjs (${blogSlugs.length} slugs), ` +
  `src/data/menopauseSeo.cjs (${MENOPAUSE_PAGES.length} pages), ` +
  `public/sitemap.xml (${STATIC_ROUTES.length + blogPosts.length} urls) and ` +
  `public/_redirects (${redirectLines.filter((l) => l && !l.startsWith('#')).length} rules).`,
);
